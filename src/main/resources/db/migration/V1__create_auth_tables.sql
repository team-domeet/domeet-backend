CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR(20) NOT NULL,
    birth_year SMALLINT,
    verified_identity_key VARCHAR(255),
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_status_check CHECK (status IN ('PENDING', 'ACTIVE', 'WITHDRAWN'))
);

CREATE TABLE social_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    provider VARCHAR(20) NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    linked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT social_accounts_provider_check CHECK (provider IN ('KAKAO', 'GOOGLE', 'APPLE')),
    CONSTRAINT social_accounts_provider_subject_key UNIQUE (provider, provider_user_id),
    CONSTRAINT social_accounts_user_provider_key UNIQUE (user_id, provider)
);
